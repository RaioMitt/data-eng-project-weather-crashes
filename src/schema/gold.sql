CREATE SCHEMA IF NOT EXISTS gold;

-- Function for converting coordinates
CREATE OR REPLACE FUNCTION gold.lest97(lon double precision, lat double precision)
RETURNS TABLE (easting double precision, northing double precision)
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
    a  CONSTANT double precision := 6378137.0;
    f  CONSTANT double precision := 1 / 298.257222101;
    e  CONSTANT double precision := sqrt(2 * (1 / 298.257222101) - power(1 / 298.257222101, 2));
    p0 CONSTANT double precision := radians(57.5175539305556);
    p1 CONSTANT double precision := radians(59.3333333333333);
    p2 CONSTANT double precision := radians(58.0);
    l0 CONSTANT double precision := radians(24.0);
    e0 CONSTANT double precision := 500000.0;
    n0 CONSTANT double precision := 6375000.0;
    m1 double precision; m2 double precision;
    t0 double precision; t1 double precision; t2 double precision; tt double precision;
    n  double precision; cf double precision; rf double precision;
    r  double precision; th double precision; p double precision;
BEGIN
    m1 := cos(p1) / sqrt(1 - power(e, 2) * power(sin(p1), 2));
    m2 := cos(p2) / sqrt(1 - power(e, 2) * power(sin(p2), 2));
    t0 := tan(pi() / 4 - p0 / 2) / power((1 - e * sin(p0)) / (1 + e * sin(p0)), e / 2);
    t1 := tan(pi() / 4 - p1 / 2) / power((1 - e * sin(p1)) / (1 + e * sin(p1)), e / 2);
    t2 := tan(pi() / 4 - p2 / 2) / power((1 - e * sin(p2)) / (1 + e * sin(p2)), e / 2);
    n  := (ln(m1) - ln(m2)) / (ln(t1) - ln(t2));
    cf := m1 / (n * power(t1, n));
    rf := a * cf * power(t0, n);
    p  := radians(lat);
    tt := tan(pi() / 4 - p / 2) / power((1 - e * sin(p)) / (1 + e * sin(p)), e / 2);
    r  := a * cf * power(tt, n);
    th := n * (radians(lon) - l0);
    easting  := e0 + r * sin(th);
    northing := n0 + rf - r * cos(th);
    RETURN NEXT;
END;
$$;

-- Drop facts first, since they depend on the dimensions
DROP TABLE IF EXISTS gold.crashes_fact_table CASCADE;
DROP TABLE IF EXISTS gold.weather_fact_table CASCADE;
DROP TABLE IF EXISTS gold.time_dimension CASCADE;
DROP TABLE IF EXISTS gold.location_dimension CASCADE;
DROP TABLE IF EXISTS gold.crash_type_dimension CASCADE;
DROP TABLE IF EXISTS gold.weather_station_dimension CASCADE;

-- Dimensions first: facts point to them, so they must exist first
CREATE TABLE gold.time_dimension (
    id         INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date       DATE NOT NULL,
    year       INTEGER NOT NULL,
    month      INTEGER NOT NULL,
    day        INTEGER NOT NULL,
    weekday    VARCHAR(20),
    hour       INTEGER NOT NULL,
    is_weekend BOOLEAN
);

CREATE TABLE gold.location_dimension (
    id           INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    county       VARCHAR(255) NOT NULL,
    municipality VARCHAR(500),
    settlement   VARCHAR(500)
);



CREATE TABLE gold.crash_type_dimension (
    id         INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crash_type VARCHAR(500)
);

CREATE TABLE gold.weather_station_dimension (
    id           INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_code VARCHAR(50) NOT NULL,
    name         VARCHAR(500) NOT NULL,
    x_coordinate NUMERIC(9,6) NOT NULL,
    y_coordinate NUMERIC(9,6) NOT NULL,
    valid_from   DATE,
    valid_to     DATE
);


-- Facts: each foreign key points from the fact to the dimension's id
CREATE TABLE gold.crashes_fact_table (
    id               INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    damage_amount    INTEGER NOT NULL,
    personal_injury  BOOLEAN NOT NULL,
    time_id          INTEGER REFERENCES gold.time_dimension(id),
    location_id      INTEGER REFERENCES gold.location_dimension(id),
    crashtype_id     INTEGER REFERENCES gold.crash_type_dimension(id),
    x_coordinate     INTEGER,
    y_coordinate     INTEGER,
    station_id       INTEGER REFERENCES gold.weather_station_dimension(id),
    damage_qualifier VARCHAR(20)
);

CREATE TABLE gold.weather_fact_table (
    id              INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    max_temperature DECIMAL,
    min_temperature DECIMAL,
    max_wind_speed  DECIMAL,
    precipitation   DECIMAL,
    sunshine        DECIMAL,
    time_id         INTEGER REFERENCES gold.time_dimension(id),
    station_id      INTEGER REFERENCES gold.weather_station_dimension(id)
);

-- Time: one row per hour, from the earliest to the latest date in either table
INSERT INTO gold.time_dimension (date, year, month, day, weekday, hour, is_weekend)
SELECT ts::date,
       EXTRACT(YEAR  FROM ts)::int,
       EXTRACT(MONTH FROM ts)::int,
       EXTRACT(DAY   FROM ts)::int,
       TRIM(TO_CHAR(ts, 'Day')),
       EXTRACT(HOUR  FROM ts)::int,
       EXTRACT(ISODOW FROM ts) IN (6, 7)
FROM generate_series(
       LEAST((SELECT MIN(date) FROM silver.crashes),
             (SELECT MIN(date) FROM silver.weather_hourly))::timestamp,
       GREATEST((SELECT MAX(date) FROM silver.crashes),
                (SELECT MAX(date) FROM silver.weather_hourly))::timestamp + interval '23 hours',
       interval '1 hour') AS ts;


-- Locations: one row per distinct county / municipality / settlement
INSERT INTO gold.location_dimension (county, municipality, settlement)
SELECT DISTINCT county, municipality, settlement
FROM silver.crashes
WHERE county IS NOT NULL;

-- Crash types: one row per distinct type
INSERT INTO gold.crash_type_dimension (crash_type)
SELECT DISTINCT crash_type
FROM silver.crashes
WHERE crash_type IS NOT NULL;

-- Weather stations: copied as they are
INSERT INTO gold.weather_station_dimension
       (station_code, name, x_coordinate, y_coordinate, valid_from, valid_to)
SELECT station_code, name, x_coordinate, y_coordinate, valid_from, valid_to
FROM silver.weather_stations;

INSERT INTO gold.crashes_fact_table
       (damage_amount, personal_injury, time_id, location_id, crashtype_id,
        x_coordinate, y_coordinate, station_id, damage_qualifier)
WITH stations AS (
    SELECT s.id, s.valid_from, s.valid_to, c.easting, c.northing
    FROM gold.weather_station_dimension s,
         LATERAL gold.lest97(s.x_coordinate::double precision,
                             s.y_coordinate::double precision) c
)
SELECT cr.damage_amount, cr.personal_injury,
       t.id, l.id, ct.id,
       cr.x_coordinate, cr.y_coordinate,
       st.id,
       cr.damage_qualifier
FROM silver.crashes cr
LEFT JOIN gold.time_dimension t
       ON t.date = cr.date
      AND t.hour = EXTRACT(HOUR FROM cr.time)::int
LEFT JOIN gold.location_dimension l
       ON l.county       IS NOT DISTINCT FROM cr.county
      AND l.municipality IS NOT DISTINCT FROM cr.municipality
      AND l.settlement   IS NOT DISTINCT FROM cr.settlement
LEFT JOIN gold.crash_type_dimension ct
       ON ct.crash_type = cr.crash_type
LEFT JOIN LATERAL (
    SELECT s.id
    FROM stations s
    WHERE cr.x_coordinate IS NOT NULL
      AND cr.y_coordinate IS NOT NULL
      AND cr.date >= COALESCE(s.valid_from, DATE '1900-01-01')
      AND cr.date <= COALESCE(s.valid_to,   DATE '9999-12-31')
    ORDER BY power(s.easting  - cr.x_coordinate, 2)
           + power(s.northing - cr.y_coordinate, 2)
    LIMIT 1
) st ON TRUE;

INSERT INTO gold.weather_fact_table
       (max_temperature, min_temperature, max_wind_speed, precipitation, sunshine,
        time_id, station_id)
SELECT w.max_temperature, w.min_temperature, w.max_wind_speed,
       w.precipitation, w.sunshine,
       t.id, s.id
FROM silver.weather_hourly w
LEFT JOIN gold.time_dimension t
       ON t.date = w.date AND t.hour = w.hour
LEFT JOIN gold.weather_station_dimension s
       ON s.station_code = w.station_code
      AND w.date >= COALESCE(s.valid_from, DATE '1900-01-01')
      AND w.date <= COALESCE(s.valid_to,   DATE '9999-12-31');